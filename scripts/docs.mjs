#!/usr/bin/env node
// TBA — hc-my-career-docs manager.
//
// CLI:
//   node docs.mjs where                  # print docs path
//   node docs.mjs init                   # create local docs skeleton if missing
//   node docs.mjs status                 # check git state (clean/dirty/untracked/no-repo)
//   node docs.mjs pull                   # git pull (if docs is a git repo)
//   node docs.mjs services               # list services from project.json or workspace discovery
//   node docs.mjs scan                   # scan all services → build snapshot JSON (no AI call)
//   node docs.mjs publish "<message>"    # git add + commit + push (only if docs is a git repo)

import { execFile } from 'node:child_process';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { existsSync, statSync } from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';
import { loadConfig } from './config.mjs';
import { scanRepo } from './scan.mjs';
import { Scout } from './ducks.mjs';

const exec = promisify(execFile);

function _expand(p) {
  if (!p) return p;
  if (p.startsWith('~')) return path.join(process.env.HOME || '', p.slice(1));
  return p;
}

async function docsRoot() {
  const cfg = await loadConfig();
  if (!cfg) throw new Error('No config. Run /tba:brief first.');
  const p = _expand(cfg.docs.localPath);
  return { root: p, workspaceRoot: _expand(cfg.workspace.root), repoPrefix: cfg.workspace.repoPrefix };
}

async function isGitRepo(p) {
  if (!existsSync(p)) return false;
  try {
    await exec('git', ['-C', p, 'rev-parse', '--git-dir'], { timeout: 3000 });
    return true;
  } catch {
    return false;
  }
}

async function projectManifest(root) {
  const manifestPath = path.join(root, 'tba', 'project.json');
  if (!existsSync(manifestPath)) return null;
  try {
    return JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch {
    return null;
  }
}

async function discoverServices({ workspaceRoot, repoPrefix }) {
  if (!existsSync(workspaceRoot)) return [];
  const { readdirSync } = await import('node:fs');
  return readdirSync(workspaceRoot)
    .filter((n) => !repoPrefix || n.startsWith(repoPrefix))
    .filter((n) => {
      const p = path.join(workspaceRoot, n);
      try { return statSync(p).isDirectory(); } catch { return false; }
    })
    .map((name) => ({ name, path: path.join(workspaceRoot, name) }));
}

export async function initDocs(scope) {
  const { root, workspaceRoot, repoPrefix } = scope || await docsRoot();
  if (existsSync(root) && existsSync(path.join(root, 'tba', 'project.json'))) {
    return { created: false, root, reason: 'already initialized' };
  }
  await mkdir(path.join(root, 'tba', 'services'), { recursive: true });
  await mkdir(path.join(root, 'guides'), { recursive: true });

  const services = await discoverServices({ workspaceRoot, repoPrefix });
  const manifest = {
    name: path.basename(root),
    createdAt: new Date().toISOString(),
    workspaceRoot,
    services: services.map((s) => ({ name: s.name, path: path.relative(root, s.path) })),
  };
  await writeFile(path.join(root, 'tba', 'project.json'), JSON.stringify(manifest, null, 2));

  if (!existsSync(path.join(root, 'README.md'))) {
    await writeFile(
      path.join(root, 'README.md'),
      `# ${path.basename(root)}\n\nShared architecture + documentation for hc-my-career services.\n\n- \`tba/project.json\` — service registry\n- \`tba/system-map.md\` — overview (generated by \`/tba:docs scan\`)\n- \`tba/services/*.md\` — per-service snapshots\n- \`guides/\` — manual docs (how-to, troubleshooting)\n`
    );
  }
  return { created: true, root, services: services.length };
}

export async function pullDocs(scope) {
  const { root } = scope || await docsRoot();
  if (!(await isGitRepo(root))) {
    return { ok: false, reason: 'not_a_git_repo', root };
  }
  const { stdout } = await exec('git', ['-C', root, 'pull', '--ff-only'], { timeout: 30000 });
  return { ok: true, root, output: stdout.trim() };
}

export async function scanAllServices(scope) {
  const sc = scope || await docsRoot();
  const manifest = (await projectManifest(sc.root)) || {
    services: (await discoverServices(sc)).map((s) => ({ name: s.name, path: s.path })),
  };
  if (!manifest.services?.length) {
    throw new Error(`No services registered. Run /tba:docs init first.`);
  }

  const scout = new Scout();
  scout.start(`Project timeline sweep — ${manifest.services.length} services`);

  const results = [];
  for (const svc of manifest.services) {
    const svcPath = path.isAbsolute(svc.path) ? svc.path : path.resolve(sc.root, svc.path);
    if (!existsSync(svcPath)) {
      scout.mark(svc.name, 'skipped');
      continue;
    }
    try {
      const snap = await scanRepo(svcPath, { scout });
      results.push({ name: svc.name, path: svcPath, ...snap });
    } catch (err) {
      scout.mark(svc.name, 'error');
    }
  }

  // Write aggregate scan cache
  const outDir = path.join(sc.root, 'tba', '.cache');
  await mkdir(outDir, { recursive: true });
  await writeFile(
    path.join(outDir, 'scan.json'),
    JSON.stringify({ scannedAt: new Date().toISOString(), services: results }, null, 2)
  );

  await scout.stop({
    final: `${results.length} services indexed → ${path.relative(process.cwd(), path.join(outDir, 'scan.json'))}`,
  });
  return { count: results.length, cache: path.join(outDir, 'scan.json'), services: results.map((r) => r.name) };
}

export async function publishDocs(message, scope) {
  const { root } = scope || await docsRoot();
  if (!(await isGitRepo(root))) {
    return { ok: false, reason: 'not_a_git_repo', root };
  }
  await exec('git', ['-C', root, 'add', '-A']);
  const { stdout: statusOut } = await exec('git', ['-C', root, 'status', '--porcelain']);
  if (!statusOut.trim()) {
    return { ok: true, nothingToCommit: true, root };
  }
  await exec('git', ['-C', root, 'commit', '-m', message], { timeout: 10000 });
  const { stdout: pushOut } = await exec('git', ['-C', root, 'push'], { timeout: 30000 });
  return { ok: true, root, output: pushOut.trim() };
}

// ─── CLI ──────────────────────────────────────────
if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, ...args] = process.argv.slice(2);
  try {
    const scope = await docsRoot();
    switch (cmd) {
      case 'where':
        console.log(scope.root);
        break;

      case 'status': {
        const exists = existsSync(scope.root);
        const isRepo = exists && (await isGitRepo(scope.root));
        const manifestExists = exists && existsSync(path.join(scope.root, 'tba', 'project.json'));
        console.log(JSON.stringify({
          root: scope.root,
          exists,
          isGitRepo: isRepo,
          initialized: manifestExists,
        }, null, 2));
        break;
      }

      case 'init': {
        const r = await initDocs(scope);
        console.log(r.created
          ? `[✓] Initialized docs at ${r.root}  (${r.services} services discovered)`
          : `[·] Already initialized: ${r.root}`
        );
        break;
      }

      case 'pull': {
        const r = await pullDocs(scope);
        if (!r.ok) console.log(`[⚠] ${r.reason}: ${r.root}`);
        else console.log(`[✓] ${r.output || 'up to date'}`);
        break;
      }

      case 'services': {
        const manifest = (await projectManifest(scope.root)) || {
          services: (await discoverServices(scope)).map((s) => ({ name: s.name, path: s.path })),
        };
        for (const s of manifest.services) {
          console.log(`  ${s.name.padEnd(40)} ${s.path}`);
        }
        break;
      }

      case 'scan': {
        const r = await scanAllServices(scope);
        console.log(`\n[◎ SCAN COMPLETE] ${r.count} services → ${r.cache}`);
        break;
      }

      case 'publish': {
        if (!args[0]) { console.error('Usage: docs.mjs publish "<message>"'); process.exit(2); }
        const r = await publishDocs(args[0], scope);
        if (!r.ok) console.log(`[⚠] ${r.reason}: ${r.root}`);
        else if (r.nothingToCommit) console.log('[·] Nothing to commit.');
        else console.log(`[✓ PUBLISHED] ${r.output}`);
        break;
      }

      default:
        console.log('Usage: docs.mjs [where|status|init|pull|services|scan|publish "msg"]');
    }
  } catch (err) {
    console.error(`[⚠ NEXUS EVENT] ${err.message}`);
    process.exit(1);
  }
}
